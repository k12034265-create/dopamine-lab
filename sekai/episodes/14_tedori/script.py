# 名前を付けた言葉：「額面マジック」（額面の数字は上がって見えるのに、天引きと物価で手元から消えていく）
# 方針：「苦しいのは本当。ただ原因は思われているのとちがう」に着地。誰か（世代・政府・会社）を悪者にしない。

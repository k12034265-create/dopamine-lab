#  - 厚労省 令和7年賃金構造基本統計調査：大卒初任給 26万2,300円（前年24万8,300円から+1万4,000円、+5.6%）
#  - 厚労省 毎月勤労統計 2025年分：名目+2.3%、CPI+3.7%、実質-1.3%（4年連続マイナス）。2025年は各月とも前年同月比マイナス（nippon.com）。2026年1〜3月は実質+1.3%（共同）
#  - 厚労省 2025年国民生活基礎調査：生活が「苦しい」55.4%、児童のいる世帯61.5%
#  - 厚生年金保険料率：本人負担 1980年1月 男性5.3%（大和総研）→ 2017年9月以降 9.15%で固定（厚労省）。健康保険は全国平均で本人5.0%（2012年度〜）
#  - 財務省 国民負担率：1970年度24.3% → 2024年度46.7%（実績）
#  - マイナビニュース試算：年収400万円・40歳独身・東京の手取り 2003年329万8,360円 → 2023年311万6,515円（約18万円減）
